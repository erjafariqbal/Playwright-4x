 //Increment Decrement Operation

 // 1. Pre-Increment/Decrement : First increment/Decrement then either assign the value or perform the operation.
   
 let a = 10;
 // ++a --> It is a Pre increment Operator . It will increase the value by 1
 // The answer will be a+1 = 11
 console.log("Pre-increment operation of a = ++a", ++a);
 

 // 2. Post-Decrement : First Perform or assign the value then increment or Decrement.

 //a++
console.log("Post-increment operation of a = a++", a++);
 //The result of a++ will be 10

 // Similerly it will happen with decrement operation
 



